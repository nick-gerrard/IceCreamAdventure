function Level.new()
	local map = {}
	for row, str in ipairs(rawMap) do
		map[row] = {}
		for col = 1, #str do
			map[row][col] = tonumber(str:sub(col, col))
		end
	end

	return setmetatable({ map = map }, Level)
end

function Level:getTile(x, y)
	local col = math.floor(x / C.TILE_SIZE) + 1
	local row = math.floor(y / C.TILE_SIZE) + 1
	if self.map[row] and self.map[row][col] then
		return self.map[row][col]
	end
	return 0
end

function Level:draw()
	for i = 1, #self.map do
		for j = 1, #self.map[i] do
			local x, y = (j - 1) * C.TILE_SIZE, (i - 1) * C.TILE_SIZE
			if self.map[i][j] > 1 then
				love.graphics.draw(skyTexture, x, y)
				love.graphics.draw(iceCream, x, y)
				love.graphics.setColor(1, 1, 1)
			elseif self.map[i][j] > 0 then
				love.graphics.draw(surfaceTexture, x, y)
				love.graphics.setColor(1, 1, 1)
			else
				love.graphics.draw(skyTexture, x, y)
				love.graphics.setColor(1, 1, 1)
			end
		end
	end
end

function Level:getMap()
	return self.map
end

function Level:collectTile(row, col)
	self.map[row][col] = 0
end

return Level
